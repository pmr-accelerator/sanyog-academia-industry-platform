import { listForStudent as listOppsForStudent } from './opportunity.js';

const DISCLAIMER = 'This roadmap is advisory guidance to help you plan your learning. It is not a prediction or guarantee of selection, placement or salary, and it does not change any eligibility rule.';

export const listTracks = () => Object.entries(TRACKS).map(([key, roles]) => ({ discipline: key, label: DISCIPLINES[key], roles: roles.map((r) => ({ role: r.role, skills: r.skills.map(([name, level]) => ({ name, level })) })) }));

async function setting(key, fallback) {
  const row = await prisma.platformSetting.findUnique({ where: { key } });
  return row ? row.value : fallback;
}

export async function generate(student, user, { targetRole, weeklyLearningHours }) {
  const track = findTrackAnywhere(targetRole);
  if (!track) throw badRequest('Choose a target role from the supported list');
  const limit = Math.min(env.AI_DAILY_LIMIT_PER_USER, Number(await setting('ai.dailyLimit', env.AI_DAILY_LIMIT_PER_USER)));
  const since = new Date(Date.now() - 24 * 3600e3);
  if ((await prisma.aiUsageLog.count({ where: { userId: user.id, feature: 'roadmap', createdAt: { gte: since } } })) >= limit) throw new AppError(429, 'AI_LIMIT', `You can generate ${limit} roadmaps per day. Try again tomorrow.`);

  const snap = await loadStudentSnapshot(student.id);
  const p = snap.profile;
  const [projectCount, certificationCount] = await Promise.all([prisma.project.count({ where: { studentId: student.id } }), prisma.certification.count({ where: { studentId: student.id } })]);
  const input = {
    discipline: p.department?.discipline || track.discipline, degree: p.degree, academicYear: p.academicYear, semester: p.semester, targetRole: track.role,
    careerInterests: (p.careerInterests || []).slice(0, 8).map((s) => String(s).slice(0, 60)), weeklyLearningHours: weeklyLearningHours || p.weeklyLearningHours || 6,
    skills: snap.snapshot.skills.map((s) => ({ name: s.name, proficiency: s.proficiency })), projectCount, certificationCount,
    trackSkills: track.skills.map(([name, level]) => ({ name, requiredLevel: level })),
  };
  const enabled = (await setting('ai.enabled', true)) !== false;
  const { roadmap, meta } = await ai.generateRoadmap(input, { skipProvider: !enabled });
  await prisma.aiUsageLog.create({ data: { userId: user.id, feature: 'roadmap', provider: meta.provider || meta.providerAttempted || 'rule-based', model: meta.model, latencyMs: meta.latencyMs, success: !meta.usedFallback || meta.reason === 'NO_PROVIDER_CONFIGURED', errorCode: meta.usedFallback ? meta.reason : null, usedFallback: meta.usedFallback } });

  // Link library resources to each milestone by skill name / discipline.
  const created = await prisma.$transaction(async (tx) => {
    await tx.roadmap.updateMany({ where: { studentId: student.id, status: 'ACTIVE' }, data: { status: 'ARCHIVED' } });
    const r = await tx.roadmap.create({
      data: {
        studentId: student.id, targetRole: track.role, source: meta.source, providerName: meta.provider, modelName: meta.model, summary: roadmap.summary,
        disclaimer: DISCLAIMER + (meta.source === 'RULE_BASED_FALLBACK' ? ' This plan was produced by the built-in rule-based generator, not by an AI model.' : ' This plan was generated by an AI model and checked for format only.'),
        inputSnapshot: input, skillGaps: roadmap.skillGaps,
      },
    });
    for (const m of roadmap.milestones) {
      const res = await tx.learningResource.findMany({ where: { status: 'ACTIVE', OR: [{ skills: { some: { name: { in: m.skills } } } }] }, take: 3, select: { id: true } });
      await tx.roadmapMilestone.create({ data: { roadmapId: r.id, position: m.position, level: m.level, title: m.title, description: m.description, targetWeek: m.targetWeek, skills: m.skills, deliverable: m.deliverable, resources: { connect: res } } });
    }
    return r;
  });
  return { id: created.id, source: meta.source, fallbackReason: meta.reason, projectIdeas: roadmap.projectIdeas, assessments: roadmap.assessments };
}

export async function getActive(student) {
  const r = await prisma.roadmap.findFirst({ where: { studentId: student.id, status: 'ACTIVE' }, orderBy: { createdAt: 'desc' }, include: { milestones: { orderBy: { position: 'asc' }, include: { resources: { select: { id: true, title: true, url: true, type: true, provider: true, licenseNote: true } } } } } });
  if (!r) return null;
  const snap = await loadStudentSnapshot(student.id);
  const have = new Map(snap.snapshot.skills.map((s) => [s.name, s.proficiency]));
  const gaps = (r.skillGaps || []).map((g) => ({ skill: g.skill, required: g.required, atGeneration: g.current, current: have.get(g.skill) || 0 }));
  const need = gaps.reduce((a, g) => a + g.required, 0);
  const got = gaps.reduce((a, g) => a + Math.min(g.required, g.current), 0);
  const done = r.milestones.filter((m) => m.status === 'COMPLETED').length;
  const label = r.source === 'AI_PROVIDER' ? `AI-generated (${r.providerName})` : 'Rule-based plan (not AI-generated)';
  return { ...r, sourceLabel: label, gaps, readinessPercent: need ? Math.round((got / need) * 100) : 0, milestoneProgress: { done, total: r.milestones.length } };
}
export const history = (student) => prisma.roadmap.findMany({ where: { studentId: student.id }, orderBy: { createdAt: 'desc' }, select: { id: true, targetRole: true, source: true, status: true, createdAt: true } });

export async function setMilestone(student, id, status) {
  const m = await prisma.roadmapMilestone.findFirst({ where: { id, roadmap: { studentId: student.id } } });
  if (!m) throw notFound();
  return prisma.roadmapMilestone.update({ where: { id }, data: { status, completedAt: status === 'COMPLETED' ? new Date() : null } });
}

// Opportunities that use the skills the roadmap is closing, filtered by the explicit eligibility engine.
export async function recommendedOpportunities(student) {
  const r = await prisma.roadmap.findFirst({ where: { studentId: student.id, status: 'ACTIVE' } });
  const { rows } = await listOppsForStudent(student, {}, { skip: 0, take: 100 });
  const gapNames = new Set((r?.skillGaps || []).map((g) => g.skill));
  return rows.filter((o) => o.eligibility !== 'NOT_ELIGIBLE')
    .map((o) => ({ ...o, why: o.skills.filter((s) => gapNames.has(s.name)).map((s) => `Uses ${s.name}, a skill in your roadmap`) }))
    .sort((a, b) => b.why.length - a.why.length || (b.matchScore ?? 0) - (a.matchScore ?? 0)).slice(0, 6);
}

export async function compare(student, a, b) {
  const A = findTrackAnywhere(a); const B = findTrackAnywhere(b);
  if (!A || !B) throw badRequest('Choose two supported roles');
  const snap = await loadStudentSnapshot(student.id);
  return compareRoles(A, B, Object.fromEntries(snap.snapshot.skills.map((s) => [s.name, s.proficiency])));
}
