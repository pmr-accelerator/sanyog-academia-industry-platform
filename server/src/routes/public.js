import { Router } from 'express';
import { z } from 'zod';
import prisma from '../db.js';
import { h, parse, pageParams, pageMeta, paged } from '../utils/http.js';
import { publicFormLimiter } from '../middleware/rateLimit.js';
import * as pub from '../services/public.js';
import * as opps from '../services/opportunity.js';
import * as resources from '../services/resources.js';
import * as credential from '../services/credential.js';
import { listTracks } from '../services/roadmap.js';
import { DISCIPLINES } from '../data/careerTracks.js';
import { email, shortText } from '../validators/common.js';

const r = Router();
r.get('/config', h(() => pub.publicConfig()));
r.get('/stats', h(() => pub.stats()));
r.get('/institutions', h(() => pub.institutionsForRegistration()));
r.get('/disciplines', h(() => Object.entries(DISCIPLINES).map(([key, label]) => ({ key, label }))));
r.get('/tracks', h(() => listTracks()));
r.get('/graph', h(() => pub.graph()));
r.get('/skill-demand', h(() => opps.skillDemand(15)));
r.get('/demo-accounts', h(() => pub.demoAccounts()));
r.get('/opportunities', h(async (req) => { const p = pageParams(req.query, 12); const { total, rows } = await opps.listPublic(req.query, p); return paged(rows, pageMeta(p, total)); }));
r.get('/opportunities/:id', h((req) => opps.getPublic(req.params.id)));
r.get('/resources', h(async (req) => { const p = pageParams(req.query, 12); const { total, rows } = await resources.list(req.query, p); return paged(rows, pageMeta(p, total)); }));
r.get('/skills', h(async (req) => prisma.skill.findMany({ where: { ...(req.query.q ? { name: { contains: String(req.query.q), mode: 'insensitive' } } : {}), ...(req.query.discipline ? { disciplines: { has: String(req.query.discipline) } } : {}) }, select: { id: true, name: true, category: true, disciplines: true, taxonomy: { select: { name: true, isOfficial: true } } }, orderBy: { name: 'asc' }, take: 100 })));
r.get('/credentials/:jti', h((req) => credential.verifyPublic(req.params.jti)));
r.post('/contact', publicFormLimiter, h((req) => pub.contact(parse(z.object({ name: shortText(100), email, subject: shortText(150), message: shortText(3000) }), req.body)), 201));
export default r;
